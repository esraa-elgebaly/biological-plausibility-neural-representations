"""## 2. Build the network

`SNN_LIFCell` is a recurrent layer of leaky integrate-and-fire neurons with:
- **Dale's law**: 80% of units are excitatory, 20% inhibitory (`ei_ratio`), enforced by masking the sign of outgoing recurrent weights.
- **Spike-frequency adaptation (SFA)**: a subset of units (`sfa_ratio`) have a rising spike threshold driven by their own recent firing, giving them longer time constants.
- Independent per-neuron voltage/current noise (a random walk in the base current, white noise in voltage) so the dynamics aren't perfectly deterministic.

Its output feeds a linear readout into a small non-spiking leaky-integrator layer (`fc_out` + `out`), which is what gets decoded into left/right.

`hidden_size=500` below is the paper's actual default — worth using now that a GPU is available, since a bigger recurrent matmul per timestep is exactly where GPU parallelism helps most.
"""

