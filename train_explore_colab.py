def condition_delay_traces(m, data_loader_obj, is_snn, n_batches=60):
    """Trial-averaged, delay-period, time-binned activity per unit, split by (rule, choice) -
    4 conditions: rule (audio/visual context) x choice (correct side/ground truth), matching
    the paper's Rule x Choice population-trajectory analysis (results_visualization.py's get_pca)."""
    m.eval()
    sums = {(c, t): None for c in (0, 1) for t in (0, 1)}
    counts = {(c, t): 0 for c in (0, 1) for t in (0, 1)}
    with torch.no_grad():
        for _ in range(n_batches):
            trials, _, desc = data_loader_obj.get_batch()
            _ = m(trials.to(device).double())
            act = bin_average(get_activity(m, is_snn)[DELAY_START:DELAY_END], BIN_SIZE)  # (bins, batch, hidden)
            for i, d in enumerate(desc):
                key = (d['c'], d['truth'])
                s = act[:, i, :]
                sums[key] = s if sums[key] is None else sums[key] + s
                counts[key] += 1
    return {key: sums[key] / counts[key] for key in sums}  # each (bins, hidden_size)


