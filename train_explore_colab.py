class VanillaRNN(torch.nn.Module):
    """The simplest possible alternative to SNN_LIFCell: a standard Elman RNN
    (tanh nonlinearity, continuous-valued hidden state) with a linear readout.
    No spiking, no Dale's-law E/I split, no spike-frequency adaptation, no
    refractory period, no injected voltage/current noise - just a recurrent
    layer mapping the same 5-channel input to the same 2-choice output."""

    def __init__(self, input_size, hidden_size, output_size, loss_step, rho=1.5):
        super().__init__()
        self.rnn = torch.nn.RNN(input_size, hidden_size, nonlinearity='tanh')
        self.readout = torch.nn.Linear(hidden_size, output_size)
        self.loss_step = loss_step
        self.recording = None  # populated on each forward() call, mirrors model.snn.recording

        with torch.no_grad():
            w_hh = self.rnn.weight_hh_l0
            spectral_radius = torch.linalg.eigvals(w_hh).abs().max()
            w_hh.mul_(rho / spectral_radius)

    def forward(self, x):
        # x: (seq_len, batch, input_size) - same layout DataGenerator produces
        h_seq, _ = self.rnn(x)                       # (seq_len, batch, hidden_size)
        self.recording = h_seq.detach()               # exposed for analysis (e.g. rule-tuning section)
        out = self.readout(h_seq)                     # (seq_len, batch, output_size)
        return out[-self.loss_step:].transpose(1, 0)   # (batch, loss_step, output_size), same shape Model() produces

