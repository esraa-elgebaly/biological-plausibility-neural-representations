"""# Leaky vanilla (current)"""

class VanillaRNN(torch.nn.Module):
    """Alternative to SNN_LIFCell: a continuous-time ("leaky") RNN with tanh nonlinearity -
    no spiking, no Dale's-law E/I split, no spike-frequency adaptation, no refractory period,
    no injected voltage/current noise. Unlike a standard hard-update Elman RNN, this keeps one
    piece of the SNN's biology: membrane leak. Each step blends in only `alpha` of the new tanh
    update and retains (1-alpha) of the previous state - alpha = dt/tau_mem, matched to the SNN's
    own membrane time constant, so this comparison isolates spiking vs. continuous dynamics as
    the one varying factor, rather than silently conflating it with leaky vs. non-leaky too."""

    def __init__(self, input_size, hidden_size, output_size, loss_step, alpha, rho=1.5):
        super().__init__()
        self.hidden_size = hidden_size
        self.loss_step = loss_step
        self.alpha = alpha  # leak fraction per timestep: (1-alpha) retained, alpha new update
        self.recording = None  # populated on each forward() call, mirrors model.snn.recording

        self.input_weights = torch.nn.Parameter(torch.randn(hidden_size, input_size) / input_size ** 0.5)
        self.bias = torch.nn.Parameter(torch.zeros(hidden_size))
        self.recurrent_weights = torch.nn.Parameter(torch.empty(hidden_size, hidden_size))
        self.readout = torch.nn.Linear(hidden_size, output_size)

        # Match SNN_LIFCell's recurrent weight init (lif_refrac_cell.py): rescale so the
        # recurrent matrix's spectral radius equals rho before training starts, instead of an
        # arbitrary uncontrolled default. Without this the SNN gets a principled dynamical
        # starting point the vanilla RNN doesn't, confounding any gap between the two with
        # initialization quality rather than the architectural differences being compared.
        with torch.no_grad():
            w = torch.randn(hidden_size, hidden_size) / hidden_size ** 0.5
            spectral_radius = torch.linalg.eigvals(w).abs().max()
            self.recurrent_weights.copy_(w * (rho / spectral_radius))

    def forward(self, x):
        # x: (seq_len, batch, input_size) - same layout DataGenerator produces
        seq_len, batch_size, _ = x.shape
        h = torch.zeros(batch_size, self.hidden_size, dtype=x.dtype, device=x.device)
        outputs, hs = [], []
        for t in range(seq_len):
            candidate = torch.tanh(x[t] @ self.input_weights.T + h @ self.recurrent_weights.T + self.bias)
            h = (1 - self.alpha) * h + self.alpha * candidate
            hs.append(h.detach())
            outputs.append(self.readout(h))
        out = torch.stack(outputs)                    # (seq_len, batch, output_size)
        self.recording = torch.stack(hs)               # (seq_len, batch, hidden_size), exposed for analysis
        return out[-self.loss_step:].transpose(1, 0)    # (batch, loss_step, output_size), same shape Model() produces


