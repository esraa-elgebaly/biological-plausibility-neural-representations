def get_readout_weight(m, is_snn):
    """The (2, hidden_size) linear-readout weight matrix, wherever it lives for this architecture.
    For the SNN, fc_out lives on the inner .snn module - model itself is just the Model() wrapper."""
    return m.snn.fc_out.weight if is_snn else m.readout.weight


def evaluate_with_dropped_units(m, dl, is_snn, drop_frac, n_batches=20):
    """Zero out drop_frac of hidden units' columns in the readout weight, evaluate accuracy, then restore -
    a simplified, architecture-uniform stand-in for the paper's synaptic-weight lesioning (see markdown above)."""
    w = get_readout_weight(m, is_snn)
    hidden_size = w.shape[1]
    n_drop = int(round(drop_frac * hidden_size))
    original = w.detach().clone()
    if n_drop > 0:
        drop_idx = np.random.choice(hidden_size, size=n_drop, replace=False)
        with torch.no_grad():
            w[:, drop_idx] = 0
    correct, _ = evaluate_model_performance(m, dl, n_batches=n_batches)
    with torch.no_grad():
        w.copy_(original)
    return correct.mean()


