    print(f'epoch {epoch+1:>3}/{epochs}  train loss {train_losses[-1]:.4f} acc {train_accs[-1]:.2f}  |  '
          f'test loss {test_losses[-1]:.4f} acc {test_accs[-1]:.2f}  |  {elapsed:.0f}s elapsed')

