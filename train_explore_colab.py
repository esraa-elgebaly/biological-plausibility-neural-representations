class VanillaRNNDale(torch.nn.Module):
    """VanillaRNN + Dale's law: each hidden unit is fixed as purely excitatory
    or purely inhibitory in its outgoing recurrent weights (sign fixed by cell
    type, only magnitude learned) - matching SNN_LIFCell's recurrent_weights_dale
    (lif_refrac_cell.py). Only excitatory units project to the readout, matching
    the SNN's read_out_mask; inhibitory units still fully drive the recurrent
    dynamics. Same spectral-radius-rho init as VanillaRNN, applied to the raw
    pre-Dale-sign matrix (same convention lif_refrac_cell.py itself uses)."""

    def __init__(self, input_size, hidden_size, output_size, loss_step, rho=1.5, ei_ratio=0.8):
        super().__init__()
        self.hidden_size = hidden_size
        self.exc_size = int(hidden_size * ei_ratio)
        self.loss_step = loss_step
        self.recording = None  # populated on each forward() call, mirrors model.snn.recording

        self.input_weights = torch.nn.Parameter(torch.randn(hidden_size, input_size) / input_size ** 0.5)
        self.bias = torch.nn.Parameter(torch.zeros(hidden_size))
        self.recurrent_weights = torch.nn.Parameter(torch.empty(hidden_size, hidden_size))
        self.readout = torch.nn.Linear(hidden_size, output_size)

        with torch.no_grad():
            w = torch.randn(hidden_size, hidden_size) / hidden_size ** 0.5
            spectral_radius = torch.linalg.eigvals(w).abs().max()
            self.recurrent_weights.copy_(w * (rho / spectral_radius))

        # fixed sign per presynaptic unit: +1 excitatory, scaled negative inhibitory
        # (scaling balances total E vs I drive, same idea as the SNN's dale_vec)
        dale_sign = torch.ones(hidden_size)
        dale_sign[self.exc_size:] = -ei_ratio / (1 - ei_ratio)
        self.register_buffer('dale_sign', dale_sign)
        self.register_buffer('no_self_mask', 1 - torch.eye(hidden_size))

        readout_mask = torch.ones(hidden_size)
        readout_mask[self.exc_size:] = 0  # only excitatory units project downstream
        self.register_buffer('readout_mask', readout_mask)

    def effective_recurrent_weights(self):
        # magnitude only - Dale's law fixes the sign, gradient descent only learns |w|
        w = torch.abs(self.recurrent_weights) * self.no_self_mask
        return w * self.dale_sign.unsqueeze(0)

    def forward(self, x):
        seq_len, batch_size, _ = x.shape
        h = torch.zeros(batch_size, self.hidden_size, dtype=x.dtype, device=x.device)
        w_rec = self.effective_recurrent_weights()
        outputs, hs = [], []
        for t in range(seq_len):
            a = x[t] @ self.input_weights.T + h @ w_rec.T + self.bias
            h = torch.tanh(a)
            hs.append(h.detach())
            outputs.append(self.readout(h * self.readout_mask))
        out = torch.stack(outputs)                    # (seq_len, batch, output_size)
        self.recording = torch.stack(hs)               # (seq_len, batch, hidden_size), exposed for analysis
        return out[-self.loss_step:].transpose(1, 0)    # (batch, loss_step, output_size)

