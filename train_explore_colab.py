def vanilla_rnn_step_fun_f32(model, x_star):
    """Step-function builder for VanillaRNN (has a torch.nn.RNN submodule)."""
    w_ih = model.rnn.weight_ih_l0.detach().float()
    w_hh = model.rnn.weight_hh_l0.detach().float()
    b_ih = model.rnn.bias_ih_l0.detach().float()
    b_hh = model.rnn.bias_hh_l0.detach().float()
    x_star = x_star.detach().float()

    def rnn_fun(h):
        return torch.tanh(w_ih @ x_star + b_ih + w_hh @ h + b_hh)
    return rnn_fun


def dale_rnn_step_fun_f32(model, x_star):
    """Step-function builder for VanillaRNNDale (hand-rolled recurrence, no .rnn submodule)."""
    w_in = model.input_weights.detach().float()
    w_rec = model.effective_recurrent_weights().detach().float()
    b = model.bias.detach().float()
    x_star = x_star.detach().float()

    def rnn_fun(h):
        return torch.tanh(w_in @ x_star + b + w_rec @ h)
    return rnn_fun


