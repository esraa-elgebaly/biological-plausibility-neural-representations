def bin_average(x, bin_size):
    """x: (seq_len, ...) -> (seq_len // bin_size, ...), averaged within each bin."""
    n_bins = x.shape[0] // bin_size
    x = x[:n_bins * bin_size]
    return x.reshape((n_bins, bin_size) + x.shape[1:]).mean(axis=1)


def get_activity(m, is_snn):
    """Most recent forward pass's (seq_len, batch, hidden_size) hidden activity:
    raw spikes for the SNN, raw tanh activation for the vanilla models."""
    return m.snn.recording.lif0.z.cpu().numpy() if is_snn else m.recording.cpu().numpy()


