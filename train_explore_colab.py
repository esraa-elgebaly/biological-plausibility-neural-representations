import time

epochs = 60        # paper default
batch_num = 200      # batches per epoch; paper default
learning_rate = 3e-4
fr_reg_value = 1e-9  # firing-rate regularization, matches main.py default (keeps units from firing at ceiling)
checkpoint_every = 10

os.makedirs('checkpoints', exist_ok=True)
optimizer = torch.optim.Adam(model.parameters(), lr=learning_rate)

train_losses, train_accs, test_losses, test_accs = [], [], [], []

def run_batch(train: bool):
    trials, tgs, _ = data_loader.get_batch()
    tgs = tgs.unsqueeze(1).repeat((1, loss_step, 1)).double()
    _, ground_truth = torch.max(tgs[:, -1], 1)
    trials, tgs, ground_truth = trials.to(device), tgs.to(device), ground_truth.to(device)

    output = model(trials)
    loss = torch.nn.functional.mse_loss(output, tgs)

    if train:
        bin_size = 5
        fr = torch.mean(model.snn.recording.lif0.z.permute(2, 0, 1), dim=-1)
        fr = torch.sum(torch.reshape(torch.mean(fr, axis=0), (-1, bin_size)), axis=1) / (dt * bin_size)
        fr_loss = fr_reg_value * torch.nn.functional.mse_loss(fr, target=torch.zeros_like(fr), reduction='sum')
        loss = loss + fr_loss

    pred = torch.argmax(output[:, -1], 1)
    acc = (ground_truth == pred).float().mean().item()
    return loss, acc

t0 = time.time()
for epoch in range(epochs):
    model.train()
    epoch_losses, epoch_accs = [], []
    for _ in range(batch_num):
        optimizer.zero_grad()
        loss, acc = run_batch(train=True)
        loss.backward()
        optimizer.step()
        epoch_losses.append(loss.item())
        epoch_accs.append(acc)

    model.eval()
    with torch.no_grad():
        t_loss, t_acc = zip(*[run_batch(train=False) for _ in range(10)])
        t_loss = [l.item() for l in t_loss]

    train_losses.append(np.mean(epoch_losses))
    train_accs.append(np.mean(epoch_accs))
    test_losses.append(np.mean(t_loss))
    test_accs.append(np.mean(t_acc))

